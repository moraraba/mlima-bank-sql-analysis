"""Run every named query in sql/task*.sql against mlima_bank.db.

Each result is saved as results/<name>.csv, and all results are collected
into results/RESULTS.md (long tables are cut to their first rows there;
the CSV always has every row).
"""
import csv
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "mlima_bank.db"
OUT = ROOT / "results"
MAX_MD_ROWS = 15


def split_queries(sql_text):
    """Yield (name, description, sql) for each '-- name:' block."""
    blocks = re.split(r"^-- name:\s*", sql_text, flags=re.M)[1:]
    for block in blocks:
        name, _, body = block.partition("\n")
        desc = []
        for line in body.splitlines():
            if line.startswith("--"):
                desc.append(line.lstrip("- ").strip())
            elif line.strip():
                break
        yield name.strip(), " ".join(desc), body.strip().rstrip(";")


def fmt(v, col=""):
    if v is None:
        return ""
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    if isinstance(v, int) and abs(v) >= 10000 and not col.endswith("_id"):
        return f"{v:,}"
    return str(v)


def to_markdown(cols, rows):
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows[:MAX_MD_ROWS]:
        lines.append("| " + " | ".join(fmt(v, c) for v, c in zip(r, cols)) + " |")
    if len(rows) > MAX_MD_ROWS:
        lines.append(f"\n*Showing {MAX_MD_ROWS} of {len(rows)} rows; full result in the CSV.*")
    return "\n".join(lines)


def main():
    OUT.mkdir(exist_ok=True)
    con = sqlite3.connect(DB)
    md = ["# Query results", "",
          "Generated by `scripts/run_queries.py` from the SQL files in `sql/`.", ""]
    for sql_file in sorted((ROOT / "sql").glob("task*.sql")):
        title = sql_file.read_text().splitlines()[0].lstrip("- ").strip()
        md += [f"## {title}", ""]
        for name, desc, sql in split_queries(sql_file.read_text()):
            cur = con.execute(sql)
            cols = [d[0] for d in cur.description]
            rows = cur.fetchall()
            with open(OUT / f"{name}.csv", "w", newline="", encoding="utf-8") as f:
                w = csv.writer(f)
                w.writerow(cols)
                w.writerows(rows)
            md += [f"### `{name}`", ""]
            if desc:
                md += [desc, ""]
            md += [f"Source: [`sql/{sql_file.name}`](../sql/{sql_file.name}) · "
                   f"CSV: [`{name}.csv`]({name}.csv)", "", to_markdown(cols, rows), ""]
            print(f"{name:<40} {len(rows):>4} rows")
    (OUT / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    con.close()


if __name__ == "__main__":
    main()
